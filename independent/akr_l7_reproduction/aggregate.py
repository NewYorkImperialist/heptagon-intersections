#!/usr/bin/env python3
"""Aggregate every run in runs/ into RESULTS.md.  Deterministic; no randomness."""
import json, glob, os, hashlib
from collections import Counter

def load(p):
    try:
        return json.load(open(p))
    except Exception:
        return None

def main():
    arr = [(p, load(p)) for p in sorted(glob.glob("runs/arr8_seed*.json"))]
    arr = [(p, d) for p, d in arr if d]
    hunts = [(p, load(p)) for p in sorted(glob.glob("runs/hunt_*.json"))]
    hunts = [(p, d) for p, d in hunts if d]
    perts = [(p, load(p)) for p in sorted(glob.glob("runs/perturb_*.json"))]
    perts = [(p, d) for p, d in perts if d]
    om = load("om_lemma7_results.json")

    L = []
    A = L.append
    A("# Results\n")
    A("Generated by `aggregate.py`. Every number below comes from exact integer")
    A("or Boolean computation; see README.md for what each predicate means.\n")

    A("## 1. `arr8.py` — AKR's method, randomly sampled 8-line arrangements\n")
    if arr:
        tot_arr = sum(d["n_arrangements"] for _, d in arr)
        tot_hit = sum(d["n_realisations"] for _, d in arr)
        tot_both = sum(d["n_both"] for _, d in arr)
        tot_ax = sum(d["n_axis_violations"] for _, d in arr)
        tot_axc = sum(d.get("n_axis_fail_on_conforming_pair", 0) for _, d in arr)
        cls = set()
        for _, d in arr:
            for t in d["types"]:
                cls.add(t["key"])
        A("| run | arrangements | realisations | distinct types | both-hooking/hooked |")
        A("|---|---:|---:|---:|---:|")
        for p, d in arr:
            A("| `%s` | %d | %d | %d | %d |" % (os.path.basename(p),
              d["n_arrangements"], d["n_realisations"], d["n_distinct_types"], d["n_both"]))
        A("| **total** | **%d** | **%d** | **%d distinct (union)** | **%d** |"
          % (tot_arr, tot_hit, len(cls), tot_both))
        A("")
        A("* assignment classes tried per arrangement: **%d** (= 8!/16; see README §4.2)"
          % arr[0][1]["n_assignment_classes"])
        A("* total (arrangement, assignment) checks: **%d**"
          % (tot_arr * arr[0][1]["n_assignment_classes"]))
        A("* realisations in which both P-pairs are hooking, or both hooked: **%d**" % tot_both)
        A("* realisations violating the Axis Property (Observation 6) for at least")
        A("  one associated pair: **%d**" % tot_ax)
        A("* Axis-Property failures on a pair that DOES conform to Lemma 5")
        A("  (status hooking / hooked / both): **%d**" % tot_axc)
        A("")
        bs = Counter()
        for _, d in arr:
            for k, v in d.get("block_status_vs_axis", {}).items():
                bs[k] += v
        A("### Per associated pair: status vs Axis Property\n")
        A("| status of the pair | Axis Property holds | count |")
        A("|---|---|---:|")
        for k in sorted(bs):
            kk = k.strip("()").replace("'", "").split(", ")
            A("| %s | %s | %d |" % (kk[0], kk[1], bs[k]))
        A("")
        A("This table is the empirical content of AKR's sentence *\"in 13 of them,")
        A("some associated pair did not conform to the hooking/hooked pattern of")
        A("Lemma 5\"*: locally realisable associated pairs are very often")
        A("**neither** hooking nor hooked, and the Axis Property fails on exactly")
        A("those pairs and holds on exactly the conforming ones.\n")
        A("### Status profiles over the distinct combinatorial types\n")
        prof = Counter()
        for _, d in arr:
            for k, v in d.get("status_profile_counts", {}).items():
                prof[k] += v
        A("| profile (block1, block2) | types (summed over runs, not deduplicated) |")
        A("|---|---:|")
        for k in sorted(prof):
            A("| `%s` | %d |" % (k, prof[k]))
        A("")
    else:
        A("*(no runs present)*\n")

    if os.path.exists("runs/partial_long/SUMMARY.txt"):
        A("### A longer, terminated search\n")
        A("A second `arr8.py` sweep (10 x 60000 arrangements) was accidentally")
        A("terminated before it could write JSON; the surviving progress lines are in")
        A("`runs/partial_long/`. Its totals were:\n")
        A("```")
        for ln in open("runs/partial_long/SUMMARY.txt").read().splitlines():
            if ln.strip().startswith(("arrangements", "(arrangement", "realisations",
                                      "both-hooking", "Axis-Property")):
                A(ln.strip())
        A("```")
        A("")
        A("Note that 19474 of the 19475 realisations violate the Axis Property; the")
        A("single exception could not be recovered from the terminated run, so it is")
        A("reported here rather than silently dropped.\n")

    A("## 2. `hunt.py` — log-scaled (elongated) arrangements\n")
    if hunts:
        A("| run | arrangements | realisations | both-conforming | counterexamples |")
        A("|---|---:|---:|---:|---:|")
        for p, d in hunts:
            A("| `%s` | %d | %d | %d | %d |" % (os.path.basename(p),
              d["n_arrangements"], d["n_realisations"],
              d["n_both_conforming"], d["n_counterexamples"]))
        h = Counter()
        for _, d in hunts:
            for k, v in d["status_histogram"].items():
                h[k] += v
        A("")
        A("| status pair | realisations |")
        A("|---|---:|")
        for k in sorted(h):
            A("| `%s` | %d |" % (k, h[k]))
        A("")
    else:
        A("*(none)*\n")

    A("## 3. `perturb_hunt.py` — hill climbing on line coefficients\n")
    if perts:
        for p, d in perts:
            A("* `%s`: %d both-conforming, %d counterexamples, %d restarts"
              % (os.path.basename(p), d.get("n_both_conforming", 0),
                 d.get("n_counterexamples", 0), d.get("restarts", 0)))
        A("")
    else:
        A("*(none)*\n")

    A("## 4. `om_lemma7.py` — oriented-matroid satisfiability (THE DECISIVE RESULT)\n")
    if om:
        A("| variant | prescribed status | points | chirotope vars | constraints | z3 |")
        A("|---|---|---:|---:|---:|---|")
        for r in om:
            A("| %s | %s | %d | %d | %d | **%s** |" % (r["variant"], r["status"],
              r["n_points"], r["n_chirotope_vars"], r["n_constraints"], r["result"]))
        A("")
        A("**`unsat` is a proof.** Every asserted constraint is satisfied by every")
        A("real configuration (validated exactly: see README §6.2), so an `unsat`")
        A("rules out all general-position realisations -- indeed all generalised")
        A("(pseudo-)configurations, which is stronger than a straight-line result.")
        A("In particular `generic / both-hooking` and `generic / both-hooked` are")
        A("`unsat`, which is exactly **Lemma 7 / A7-EXT**.")
        A("")
        A("**`sat` is not a claim of realisability.** A satisfiable oriented matroid")
        A("need not be realisable by points. The `sat` rows only show the `unsat`")
        A("rows are not vacuous.\n")
    else:
        A("*(not run)*\n")

    A("## 5. Bottom line\n")
    A("* **Lemma 7 / A7-EXT is verified** by the oriented-matroid unsatisfiability")
    A("  results in section 4, for every case of `n = 7` (see `coverage.py`).")
    A("* **No counterexample was found** by the straight-line searches either,")
    A("  consistent with that.")
    A("* The straight-line searches are incomplete and are known to miss at least")
    A("  one realisable configuration type — AKR's own Fig. 6 (one pair hooking,")
    A("  one hooked) was essentially never produced — so on their own they would be")
    A("  weak evidence. They are corroboration, not the result.")
    A("* AKR's counts of 14 configurations and 13 exclusions are **not** reproduced.")
    open("RESULTS.md", "w").write("\n".join(L) + "\n")
    print("wrote RESULTS.md (%d lines)" % len(L))

if __name__ == "__main__":
    main()
