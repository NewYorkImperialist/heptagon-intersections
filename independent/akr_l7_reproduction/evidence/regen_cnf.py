#!/usr/bin/env python3
"""Regenerate all 20 DIMACS CNFs from evidence/tools/indep_om.py (pure Python,
no SAT solver needed) and compare SHA-256 against evidence/SHA256SUMS.txt.

This is what makes it safe to gitignore the 19 MB of .cnf files: they are an
exact, deterministic function of indep_om.py, which IS tracked.
Usage:  python3 regen_cnf.py [--write OUTDIR]
"""
import hashlib, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "shims"))
sys.path.insert(0, os.path.join(HERE, "tools"))
import indep_om

VARIANTS = ["generic", "P-adj", "Q-adj", "PQ-adj"]
STATUSES = ["none", "mixed-1", "mixed-2", "both-hooking", "both-hooked"]

def dimacs(variant, which):
    pts, segs, pat = indep_om.model(variant)
    E = indep_om.build(pts, segs, pat, indep_om.statuses(segs, which))
    return "p cnf %d %d\n" % (E.nv, len(E.cls)) + \
           "".join(" ".join(map(str, c)) + " 0\n" for c in E.cls)

def load_manifest():
    path = os.path.join(HERE, "SHA256SUMS.txt")
    if not os.path.isfile(path):
        sys.exit("FATAL: missing manifest %s" % path)
    m = {}
    for line in open(path):
        line = line.strip()
        if not line or line.startswith("#"): continue
        h, name = line.split(None, 1)
        m[os.path.basename(name.strip())] = h
    return m

def main():
    outdir = None
    if len(sys.argv) > 2 and sys.argv[1] == "--write":
        outdir = sys.argv[2]; os.makedirs(outdir, exist_ok=True)
    man = load_manifest()
    bad = []
    for v in VARIANTS:
        for s in STATUSES:
            tag = "%s_%s.cnf" % (v, s)
            text = dimacs(v, s)
            h = hashlib.sha256(text.encode()).hexdigest()
            if outdir:
                open(os.path.join(outdir, tag), "w").write(text)
            exp = man.get(tag)
            if exp is None:
                bad.append("%s: not in manifest" % tag); status = "NOT-IN-MANIFEST"
            elif exp != h:
                bad.append("%s: sha256 mismatch\n   expected %s\n   got      %s" % (tag, exp, h))
                status = "SHA MISMATCH"
            else:
                status = "sha256 OK"
            print("%-24s %-14s %s" % (tag, status, h), flush=True)
    if bad:
        print("\n*** %d CNF REGENERATION FAILURE(S) ***" % len(bad))
        for x in bad: print("  " + x)
        sys.exit(1)
    print("\nOK: all 20 CNFs regenerated byte-identically from indep_om.py")

main()
