"""Generate the sharded Lean proof of (E7a) exhaustiveness; run from the repo root.

The statement is `exceptionalPolygons = expectedPolygons`: among all
135 x 360 = 48,600 (order-type representative, cyclic vertex order) candidates,
exactly 16 give a simple heptagon with no uncrossable four-subset of sides.

A single `decide +kernel` on that statement does not finish.  One representative
costs about three minutes of kernel reduction, so the enumeration is split into
135 independent modules, one per representative, which `lake` builds in
parallel; a final module assembles them by rewriting, with no enumeration of its
own.  The expected hits are recomputed here from the order-type database rather
than transcribed.
"""
from pathlib import Path
from itertools import combinations, permutations
import json, hashlib, re, sys

ROOT = Path('.')
ONLY_ASSEMBLY = '--only-assembly' in sys.argv
otp = ROOT / 'data/order_types/order_types_7.json'
d = json.loads(otp.read_bytes())
vs = d['chirotopes']
TRIP = list(combinations(range(7), 3))
assert len(vs) == 135 and d['triple_order'] == list(map(list, TRIP))
IDX = {t: i for i, t in enumerate(TRIP)}
DIGEST = hashlib.sha256(otp.read_bytes()).hexdigest()

CYCLES = [(0,) + p for p in permutations(range(1, 7)) if p[0] < p[-1]]
assert len(CYCLES) == 360

def chi_of(v):
    def chi(a, b, c):
        if len({a, b, c}) < 3:
            return 0
        p, s = [a, b, c], 1
        for i in range(3):
            for j in range(i + 1, 3):
                if p[i] > p[j]:
                    p[i], p[j] = p[j], p[i]; s = -s
        return s * v[IDX[tuple(p)]]
    return chi

def is_simple(chi):
    for i in range(7):
        for j in range(i + 1, 7):
            if len({i, (i+1) % 7, j, (j+1) % 7}) < 4:
                continue
            if (chi(i, (i+1) % 7, j) != chi(i, (i+1) % 7, (j+1) % 7)
                    and chi(j, (j+1) % 7, i) != chi(j, (j+1) % 7, (i+1) % 7)):
                return False
    return True

FOURS = sorted(sum(1 << i for i in t) for t in combinations(range(7), 4))

def is_exceptional(chi):
    fam = set()
    for i, j in permutations(range(7), 2):
        L = sum(1 << k for k in range(7) if k != i and k != j and chi(i, j, k) > 0)
        for e in (0, 1 << i, 1 << j, (1 << i) | (1 << j)):
            A = L | e
            fam.add(sum(1 << s for s in range(7)
                        if bool(A >> s & 1) != bool(A >> ((s+1) % 7) & 1)))
    fam.add(0)
    return all(any((t & m) == t for m in fam) for t in FOURS)

hits = {i: [] for i in range(135)}
for i, v in enumerate(vs):
    base = chi_of(v)
    for j, cyc in enumerate(CYCLES):
        chi = (lambda cy: (lambda a, b, c: base(cy[a], cy[b], cy[c])))(cyc)
        if is_simple(chi) and is_exceptional(chi):
            hits[i].append(j)
flat = [(i, j) for i in range(135) for j in hits[i]]
print(f'recomputed hits: {len(flat)} pairs over {sum(1 for i in hits if hits[i])} representatives')

HDR = f"""/-
(E7a) EXHAUSTIVENESS, shard {{shard}}.
Generated by python3 python/classification/gen_lean_enum_shards.py
Source: data/order_types/order_types_7.json
SHA-256: {DIGEST}
The kernel checks the Lean transcription, not JSON or the generator.
Scope: this settles which of the 135 stored representatives, under which cyclic
vertex order, give an exceptional simple heptagon. COMPLETENESS OF THE
135-REPRESENTATIVE LIST IS NOT PROVED HERE and remains an external obligation,
as does any geometric reading of the halfplane test.
-/
"""

if not ONLY_ASSEMBLY:
  (ROOT / 'lean/OTEnumShard.lean').write_text(HDR.format(shard='common definitions') + """import OrderTypeClassification
set_option maxRecDepth 4000000
set_option maxHeartbeats 0
namespace Heptagon.OTEnum
open Heptagon.OrderTypeClassification

/-- The hits contributed by representative `i` over a given set of cyclic
orders.  Taking the orders as an argument is what lets the search be split: one
`decide +kernel` over all 360 at once grows a whnf cache past 1 GB and slows
down badly, while quarters stay small.  See docs/verification-status.md row 33. -/
def enumPart (i : Nat) (cs : List (Nat × List Nat)) : List (Nat × Nat) :=
  let v := orderSigns i
  cs.filterMap fun p =>
    let chi := relabel v p.2
    if simple chi && exceptional chi then some (i, p.1) else none

/-- The hits of `exceptionalPolygons` contributed by representative `i`. -/
def enumRep (i : Nat) : List (Nat × Nat) := enumPart i cyclesIdx

/-- The 360 cyclic orders in four blocks of 90. -/
def cyclesIdxA : List (Nat × List Nat) := cyclesIdx.take 90
def cyclesIdxB : List (Nat × List Nat) := (cyclesIdx.drop 90).take 90
def cyclesIdxC : List (Nat × List Nat) := (cyclesIdx.drop 180).take 90
def cyclesIdxD : List (Nat × List Nat) := cyclesIdx.drop 270

theorem cyclesIdx_split :
    cyclesIdx = cyclesIdxA ++ cyclesIdxB ++ cyclesIdxC ++ cyclesIdxD := by decide

/-- and therefore the per-representative search splits the same way. -/
theorem enumRep_eq_parts (i : Nat) :
    enumRep i = enumPart i cyclesIdxA ++ enumPart i cyclesIdxB ++
                enumPart i cyclesIdxC ++ enumPart i cyclesIdxD := by
  conv_lhs => rw [enumRep, cyclesIdx_split]
  simp only [enumPart, List.filterMap_append, List.append_assoc]

/-- The enumeration splits by representative, definitionally: no content, it is
the same term regrouped, and it is what lets the 135 shards be independent. -/
theorem exceptionalPolygons_eq_flatMap :
    exceptionalPolygons = (List.range 135).flatMap enumRep := rfl

end Heptagon.OTEnum
""")

BLOCKS = ['A', 'B', 'C', 'D']
for i in (range(135) if not ONLY_ASSEMBLY else []):
    for bi, blk in enumerate(BLOCKS):
        lo, hi2 = 90*bi, 90*(bi+1)
        sub = [j for j in hits[i] if lo <= j < hi2]
        lit = '[' + ', '.join(f'({i}, {j})' for j in sub) + ']'
        (ROOT / f'lean/OTEnum{i:03d}{blk}.lean').write_text(
            HDR.format(shard=f'representative {i} of 135, cyclic orders {lo}..{hi2-1}') +
            f"""import OTEnumShard
set_option maxRecDepth 4000000
set_option maxHeartbeats 0
namespace Heptagon.OTEnum

/-- Cyclic orders {lo}..{hi2-1} of representative {i}, decided in the kernel. -/
theorem enumPart_{i}{blk} : enumPart {i} cyclesIdx{blk} = ({lit} : List (Nat × Nat)) := by
  decide +kernel

end Heptagon.OTEnum
""")

imports = '\n'.join(f'import OTEnum{i:03d}{b}' for i in range(135) for b in BLOCKS)
lemmas = ',\n             '.join(['enumRep_eq_parts'] +
    [f'enumPart_{i}{b}' for i in range(135) for b in BLOCKS])
rng = '[' + ', '.join(str(i) for i in range(135)) + ']'
(ROOT / 'lean/OTEnumAll.lean').write_text(
    HDR.format(shard='assembly') + f"""{imports}
set_option maxRecDepth 4000000
set_option maxHeartbeats 0
namespace Heptagon.OTEnum
open Heptagon.OrderTypeClassification

/-- **(E7a), exhaustiveness.** Among all 135 x 360 = 48,600 candidates, exactly
the 16 pairs of `expectedPolygons` give a simple heptagon with no uncrossable
four-subset of sides.  Assembled by rewriting from the 135 shards; this proof
runs no enumeration of its own. -/
theorem exceptionalPolygons_eq_expected :
    exceptionalPolygons = expectedPolygons := by
  rw [exceptionalPolygons_eq_flatMap,
      show (List.range 135 : List Nat) = {rng} from rfl]
  simp only [List.flatMap_cons, List.flatMap_nil,
             {lemmas},
             List.nil_append, List.append_nil, List.cons_append]
  rfl

/-- The classification restated in the form `verification-status.md` row 5 uses:
the enumeration over the 135 stored representatives yields exactly **16**
labelled exceptional heptagons, each reduces by an explicit dihedral relabelling
to one of the stored class chirotopes, and all **14** classes occur.  The 16 are
now the enumeration's own output rather than a list supplied to it. -/
theorem sixteen_labelled_fourteen_classes :
    exceptionalPolygons.length = 16 ∧
    reductions.map (fun w => (w.rep, w.cycle)) = exceptionalPolygons ∧
    (reductions.map (fun w => w.cls)).toFinset = Finset.range 14 := by
  refine ⟨?_, ?_, expected_reductions_checked.2.1⟩
  · rw [exceptionalPolygons_eq_expected]; rfl
  · rw [exceptionalPolygons_eq_expected]; exact expected_reductions_checked.1

end Heptagon.OTEnum
""")

# lakefile: replace any previous shard block, and extend defaultTargets
lf = ROOT / 'lean/lakefile.toml'
s = lf.read_text()
MARK = '\n# --- BEGIN generated E7(a) enumeration shards ---\n'
END = '# --- END generated E7(a) enumeration shards ---\n'
if MARK in s:
    s = s[:s.index(MARK)] + s[s.index(END) + len(END):]
names = ['OTEnumShard'] + [f'OTEnum{i:03d}{b}' for i in range(135) for b in BLOCKS] + ['OTEnumAll']
block = MARK + '# Generated by python3 python/classification/gen_lean_enum_shards.py\n'
block += ''.join(f'\n[[lean_lib]]\nname = "{n}"\n' for n in names) + END
s = s.rstrip('\n') + '\n' + block
m = re.search(r'defaultTargets = \[([^\]]*)\]', s)
cur = [x.strip().strip('"') for x in m.group(1).split(',')]
cur = [c for c in cur if not c.startswith('OTEnum')] + names
s = s[:m.start()] + 'defaultTargets = [' + ', '.join(f'"{c}"' for c in cur) + ']' + s[m.end():]
lf.write_text(s)
libs = re.findall(r'\[\[lean_lib\]\]\s*\nname = "([^"]+)"', s)
dflt = [x.strip().strip('"') for x in re.search(r'defaultTargets = \[([^\]]*)\]', s).group(1).split(',')]
assert sorted(libs) == sorted(dflt), sorted(set(libs) ^ set(dflt))
print(f'wrote {len(names)} Lean modules; lakefile declares {len(libs)}, all default targets')
