"""Generate the Lean proof of the 6007 / 319 / 16 stratification.

docs/verification-status.md row 5 records that the 6,342 simple heptagons split
as 6,007 with some uncrossable 3-subset of sides, 319 with none of those but an
uncrossable 4-subset, and 16 with neither -- the exceptional ones.  The 6,342
and the 16 are already Lean theorems (rows 36 and 32); this makes the split one
too, so every number row 5 quotes is kernel-checked.

Sharded one representative per module, for the reason in row 33.
"""
from pathlib import Path
from itertools import combinations, permutations
import json, re, sys

ONLY_ASSEMBLY = '--only-assembly' in sys.argv

ots = json.load(open('data/order_types/order_types_7.json'))['chirotopes']
TRIP = list(combinations(range(7), 3)); IDX = {t: i for i, t in enumerate(TRIP)}
CY = [(0,) + p for p in permutations(range(1, 7)) if p[0] < p[-1]]
THREE = sorted(sum(1 << i for i in t) for t in combinations(range(7), 3))
FOUR = sorted(sum(1 << i for i in t) for t in combinations(range(7), 4))

def mk(v):
    def chi(a, b, c):
        if len({a, b, c}) < 3: return 0
        p, s = [a, b, c], 1
        for i in range(3):
            for j in range(i + 1, 3):
                if p[i] > p[j]: p[i], p[j] = p[j], p[i]; s = -s
        return s * v[IDX[tuple(p)]]
    return chi

def simple(chi):
    for i in range(7):
        for j in range(i + 1, 7):
            if len({i, (i+1) % 7, j, (j+1) % 7}) < 4: continue
            if (chi(i, (i+1) % 7, j) != chi(i, (i+1) % 7, (j+1) % 7)
                    and chi(j, (j+1) % 7, i) != chi(j, (j+1) % 7, (i+1) % 7)):
                return False
    return True

def fam(chi):
    out = set()
    for i, j in permutations(range(7), 2):
        L = sum(1 << k for k in range(7) if k != i and k != j and chi(i, j, k) > 0)
        for e in (0, 1 << i, 1 << j, (1 << i) | (1 << j)):
            A = L | e
            out.add(sum(1 << s for s in range(7)
                        if bool(A >> s & 1) != bool(A >> ((s+1) % 7) & 1)))
    out.add(0)
    return out

def stratum(chi):
    F = fam(chi)
    if not all(any((t & m) == t for m in F) for t in THREE): return 0
    if not all(any((t & m) == t for m in F) for t in FOUR): return 1
    return 2

counts = []
for v in ots:
    b = mk(v); c = [0, 0, 0]
    for cy in CY:
        chi = (lambda cy: (lambda a, x, z: b(cy[a], cy[x], cy[z])))(cy)
        if simple(chi): c[stratum(chi)] += 1
    counts.append(c)
tot = [sum(c[k] for c in counts) for k in range(3)]
assert tot == [6007, 319, 16], tot
print(f'stratification computed: {tot}, total {sum(tot)}')

HDR = """/-
THE 6007 / 319 / 16 STRATIFICATION -- {shard}.
Generated by python3 python/classification/gen_lean_stratification.py

docs/verification-status.md row 5 records that the 6,342 simple heptagons split
as 6,007 with some uncrossable 3-subset of sides, 319 with none of those but an
uncrossable 4-subset, and 16 with neither.  The 6,342 and the 16 are already
Lean theorems; this makes the split one too.

SCOPE.  These are predicates on chirotopes.  "Uncrossable" here is the STRICT
reading -- a subset of sides is crossable when some member of the halfplane
crossing family contains it -- which is the reading the project uses and
justifies; see docs/reviewer-guide.md 6.5.  That any of this characterises
polygons in the plane is NOT proved.
-/
"""

Path('lean/StratificationDefs.lean').write_text(HDR.format(shard='definitions') + f"""import OTEnumShard
set_option maxRecDepth 4000000
set_option maxHeartbeats 0
namespace Heptagon.Stratification
open Heptagon.OrderTypeClassification Heptagon.ClassDataFromChirotope

/-- The 35 three-element side masks. -/
def threeMasks : List Nat := {THREE}

theorem threeMasks_eq : threeMasks =
    (List.range 128).filter (fun t =>
      ((List.range 7).filter fun i => t.testBit i).length == 3) := by decide

/-- Every mask in `ms` is contained in some member of the family `F`. -/
def coveredBy (ms F : List Nat) : Bool :=
  ms.all fun t => F.any fun m => (t &&& m) == t

/-- 0 = some 3-subset uncrossable; 1 = none of those but some 4-subset
uncrossable; 2 = neither, i.e. exceptional. -/
def stratum (chi : Nat → Nat → Nat → Int) : Nat :=
  let F := famRaw chi
  if !coveredBy threeMasks F then 0 else if !coveredBy fourMasks F then 1 else 2

/-- Stratum 2 implies the `exceptional` test of `OrderTypeClassification`, so
the 16 counted here are the 16 counted there.  Only this direction is stated:
the converse needs "every 4-subset covered implies every 3-subset covered",
which is true but is a lemma about the family, not a definitional unfolding, and
nothing here needs it. -/
theorem exceptional_of_stratum_two (chi : Nat → Nat → Nat → Int) :
    stratum chi = 2 → exceptional chi = true := by
  unfold stratum exceptional exceptionalOf coveredBy
  cases h3 : (threeMasks.all fun t => (famRaw chi).any fun m => (t &&& m) == t) <;>
  cases h4 : (fourMasks.all fun t => (famRaw chi).any fun m => (t &&& m) == t) <;>
  simp [h3, h4]

/-- The stratum of each simple heptagon among the given cyclic orders, in one
pass -- computing the three counts separately would run `stratum` three times. -/
def strataOf (i : Nat) (cs : List (Nat × List Nat)) : List Nat :=
  let v := orderSigns i
  cs.filterMap fun p =>
    let chi := relabel v p.2
    if simple chi then some (stratum chi) else none

/-- The three counts, from that one pass. -/
def countStrata (l : List Nat) : List Nat :=
  [(l.filter (· == 0)).length, (l.filter (· == 1)).length, (l.filter (· == 2)).length]

def add3 (a b : List Nat) : List Nat :=
  [a.getD 0 0 + b.getD 0 0, a.getD 1 0 + b.getD 1 0, a.getD 2 0 + b.getD 2 0]

end Heptagon.Stratification
""")

BLOCKS = ['A', 'B', 'C', 'D']
blockcounts = {}
for i, v in enumerate(ots):
    b = mk(v)
    for bi in range(4):
        c = [0, 0, 0]
        for cy in CY[90*bi:90*(bi+1)]:
            chi = (lambda cy: (lambda a, x, z: b(cy[a], cy[x], cy[z])))(cy)
            if simple(chi): c[stratum(chi)] += 1
        blockcounts[(i, bi)] = c

names = []
for i in range(135):
    for bi, blk in enumerate(BLOCKS):
        name = f'Strat{i:03d}{blk}'
        names.append(name)
        lit = '[' + ', '.join(str(x) for x in blockcounts[(i, bi)]) + ']'
        if not ONLY_ASSEMBLY:
          Path(f'lean/{name}.lean').write_text(
            HDR.format(shard=f'representative {i}, cyclic orders {90*bi}..{90*(bi+1)-1}') +
f"""import StratificationDefs
set_option maxRecDepth 4000000
set_option maxHeartbeats 0
namespace Heptagon.Stratification
open Heptagon.OrderTypeClassification Heptagon.OTEnum

theorem strat_{i}{blk} : countStrata (strataOf {i} cyclesIdx{blk}) = {lit} := by
  decide +kernel

end Heptagon.Stratification
""")

imports = '\n'.join(f'import {n}' for n in names)
lemmas = ',\n             '.join(f'strat_{i}{b}' for i in range(135) for b in BLOCKS)
blocklist = ',\n   '.join(f'countStrata (strataOf {i} cyclesIdx{b})'
                          for i in range(135) for b in BLOCKS)
blocklits = ',\n   '.join('[' + ', '.join(str(x) for x in blockcounts[(i, bi)]) + ']'
                          for i in range(135) for bi in range(4))
Path('lean/StratificationAll.lean').write_text(HDR.format(shard='assembly') + f"""{imports}
set_option maxRecDepth 4000000
set_option maxHeartbeats 0
namespace Heptagon.Stratification
open Heptagon.OrderTypeClassification Heptagon.OTEnum

/-- The per-block stratum counts, in one list. -/
def blockCounts : List (List Nat) :=
  [{blocklist}]

/-- Rewritten away by the {len(names)} block lemmas, and by nothing else -- in
particular the search is never re-run here. -/
theorem blockCounts_eq : blockCounts = [{blocklits}] := by
  simp only [blockCounts, {lemmas}]

/-- The three stratum totals. -/
def totals : List Nat :=
  [(blockCounts.map (fun c => c.getD 0 0)).sum,
   (blockCounts.map (fun c => c.getD 1 0)).sum,
   (blockCounts.map (fun c => c.getD 2 0)).sum]

/-- **The 6,342 simple heptagons split 6,007 / 319 / 16.**  Every number
`verification-status.md` row 5 quotes is now kernel-checked.  Assembled from the
{len(names)} block lemmas by rewriting; this proof runs no search of its own --
after `blockCounts_eq` only additions of literals remain. -/
theorem stratification : totals = [6007, 319, 16] := by
  simp only [totals, blockCounts_eq]
  rfl

end Heptagon.Stratification
""")
print(f'wrote StratificationDefs + {len(names)} shards + StratificationAll')

lf = Path('lean/lakefile.toml'); s = lf.read_text()
MARK = '\n# --- BEGIN generated stratification shards ---\n'
END = '# --- END generated stratification shards ---\n'
if MARK in s:
    s = s[:s.index(MARK)] + s[s.index(END) + len(END):]
allnames = ['StratificationDefs'] + names + ['StratificationAll']
s = s.rstrip('\n') + '\n' + MARK + '# Generated by python3 python/classification/gen_lean_stratification.py\n' \
    + ''.join(f'\n[[lean_lib]]\nname = "{n}"\n' for n in allnames) + END
m = re.search(r'defaultTargets = \[([^\]]*)\]', s)
cur = [x.strip().strip('"') for x in m.group(1).split(',')]
cur = [c for c in cur if not (c.startswith('Strat'))] + allnames
s = s[:m.start()] + 'defaultTargets = [' + ', '.join(f'"{c}"' for c in cur) + ']' + s[m.end():]
lf.write_text(s)
libs = re.findall(r'\[\[lean_lib\]\]\s*\nname = "([^"]+)"', s)
dflt = [x.strip().strip('"') for x in re.search(r'defaultTargets = \[([^\]]*)\]', s).group(1).split(',')]
assert sorted(libs) == sorted(dflt), sorted(set(libs) ^ set(dflt))
print(f'lakefile: {len(libs)} libs')
