"""Generate lean/ClassDataFields.lean; run from the repository root.

Completes the (E7b) half of the exceptional-classification obligation.
`ClassDataFromChirotope.lean` already recomputes `M_set` and the
inclusion-maximal crossing sets from each stored `canonical_chirotope`.  The
other two stored `ClassData` fields are `lemma2_windows` and `avoiding_pairs`,
and the second is load-bearing: `AvoidingFlag.lean` checks the 225 endgame
certificates against it.  This module recomputes both from the chirotope and
proves they equal the stored fields, for all 14 classes.

This is a SEPARATE module rather than an addition to `ClassDataFromChirotope`
so that adding it does not invalidate the 135 OTEnum* enumeration shards.
"""
from pathlib import Path
import json, hashlib

p = Path('data/exceptional_profiles/exceptional_profiles_14.json')
d = json.loads(p.read_bytes())
cs = d['classes']
assert len(cs) == 14
DIGEST = hashlib.sha256(p.read_bytes()).hexdigest()

s = f'''/-
(E7b), the remaining two stored class-data fields.
Generated by python3 python/classification/gen_lean_class_fields.py
Source: data/exceptional_profiles/exceptional_profiles_14.json
SHA-256: {DIGEST}
The kernel checks the Lean transcription, not JSON or the generator.

`ClassDataFromChirotope` recomputes M and the maximal crossing sets from each
stored chirotope.  This module does the same for the other two fields,
`lemma2_windows` and `avoiding_pairs`.  The second matters beyond bookkeeping:
`AvoidingFlag.lean` (interface I3) checks the 225 endgame certificates against
`avoidingPairs`, and until now that table was read from JSON rather than
derived.

SCOPE.  This says the stored data is what the chirotope determines.  It does
NOT say the 14 classes are the right classes, that a configuration belongs to
the class its certificate names, or what "avoiding" means about an actual
polygon in the plane -- the development still has no geometric definition of
that.  Those remain open; see docs/verification-status.md rows 13 and 32.
-/
import ClassDataFromChirotope

set_option maxRecDepth 1000000
set_option maxHeartbeats 0
namespace Heptagon.ClassDataFields
open ClassDataFromChirotope ClassInvariant

/-- Transcription of `inside_tri` in python/core/chiro.py:
`chi(a,b,p) == chi(b,c,p) == chi(c,a,p)`. -/
def insideTri (chi : Nat → Nat → Nat → Int) (p a b c : Nat) : Bool :=
  chi a b p == chi b c p && chi b c p == chi c a p

/-- Transcription of `line_cuts_seg` in python/core/chiro.py:
`chi(c,d,a) != chi(c,d,b)`. -/
def lineCutsSeg (chi : Nat → Nat → Nat → Int) (c d a b : Nat) : Bool :=
  chi c d a != chi c d b

/-- The Lemma-2 windows, transcribed from the `W` loop of `classdata()` in
python/classification/export_profiles.py.  Python collects a set and sorts it;
filtering `List.range 7` gives the same list in the same order. -/
def windowsOf (chi : Nat → Nat → Nat → Int) : List Nat :=
  (List.range 7).filter fun i =>
    insideTri chi ((i+3)%7) i ((i+1)%7) ((i+2)%7) ||
    insideTri chi ((i+1)%7) ((i+4)%7) ((i+3)%7) ((i+2)%7)

/-- The avoiding pairs, transcribed from the `AV` loop of `classdata()`:
non-adjacent side pairs `i < j` where neither supporting line cuts the other
segment.  The nested loop order is Python's, so the lists match as lists. -/
def avoidingOf (chi : Nat → Nat → Nat → Int) : List (Nat × Nat) :=
  (List.range 7).flatMap fun i =>
    (List.range 7).filterMap fun j =>
      if i < j && (j - i) % 7 != 1 && (j - i) % 7 != 6 then
        (if !lineCutsSeg chi j ((j+1)%7) i ((i+1)%7) &&
            !lineCutsSeg chi i ((i+1)%7) j ((j+1)%7) then some (i,j) else none)
      else none

def storedWindows : Nat → List Nat
'''
for c in cs:
    s += f"  | {c['class_index']} => {list(c['lemma2_windows'])}\n"
s += '  | _ => []\n\ndef storedAvoiding : Nat → List (Nat × Nat)\n'
for c in cs:
    lit = '[' + ', '.join(f'({a}, {b})' for a, b in c['avoiding_pairs']) + ']'
    s += f"  | {c['class_index']} => {lit}\n"
s += '''  | _ => []

/-- **Both remaining class-data fields are recomputed from the chirotope and
agree with the stored tables, for all 14 classes.**  Together with
`ClassDataFromChirotope.recomputed_eq` this covers every field of `ClassData`
that the development consumes. -/
theorem fields_recomputed_eq : ∀ c : Fin 14,
    windowsOf (chiro (signs c)) = storedWindows c ∧
    avoidingOf (chiro (signs c)) = storedAvoiding c := by decide +kernel

/-- The stored avoiding-pair table that `AvoidingFlag.lean` checks the 225
endgame certificates against is therefore chirotope-derived, not merely read
from JSON. -/
theorem avoiding_table_derived : ∀ c : Fin 14,
    storedAvoiding c = avoidingOf (chiro (signs c)) := fun c =>
  ((fields_recomputed_eq c).2).symm

end Heptagon.ClassDataFields
'''
Path('lean/ClassDataFields.lean').write_text(s)
print('wrote lean/ClassDataFields.lean')
