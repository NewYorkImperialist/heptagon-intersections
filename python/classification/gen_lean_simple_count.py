"""Generate the Lean proof that there are exactly 6342 simple heptagons.

`docs/verification-status.md` row 5 quotes 6,342 as the number of simple
heptagons over the 135 order-type representatives, externally cross-checked
against `hamilt07.b08`.  The (E7a) enumeration evaluates `simple` on all 48,600
candidates but never counts them, so the figure was not itself a Lean theorem.
This makes it one, completing the chain 6,342 simple -> 16 exceptional -> 14
classes entirely inside the kernel.

Sharded in groups of REPS representatives, for the reason recorded in
docs/verification-status.md row 33.
"""
from pathlib import Path
from itertools import combinations, permutations
import json, re, sys

REPS = 5
ots = json.load(open('data/order_types/order_types_7.json'))['chirotopes']
TRIP = list(combinations(range(7), 3)); IDX = {t: i for i, t in enumerate(TRIP)}
CY = [(0,) + p for p in permutations(range(1, 7)) if p[0] < p[-1]]

def mk(v):
    def chi(a, b, c):
        if len({a, b, c}) < 3: return 0
        p, s = [a, b, c], 1
        for i in range(3):
            for j in range(i + 1, 3):
                if p[i] > p[j]: p[i], p[j] = p[j], p[i]; s = -s
        return s * v[IDX[tuple(p)]]
    return chi

def simple(chi):
    for i in range(7):
        for j in range(i + 1, 7):
            if len({i, (i+1) % 7, j, (j+1) % 7}) < 4: continue
            if (chi(i, (i+1) % 7, j) != chi(i, (i+1) % 7, (j+1) % 7)
                    and chi(j, (j+1) % 7, i) != chi(j, (j+1) % 7, (i+1) % 7)):
                return False
    return True

counts = []
for v in ots:
    b = mk(v)
    counts.append(sum(1 for cy in CY
                      if simple((lambda cy: (lambda a, x, c: b(cy[a], cy[x], cy[c])))(cy))))
assert sum(counts) == 6342, sum(counts)
print(f'per-representative simple counts computed; total {sum(counts)}')

HDR = """/-
THE 6,342 SIMPLE HEPTAGONS -- {shard}.
Generated by python3 python/classification/gen_lean_simple_count.py

docs/verification-status.md row 5 quotes 6,342 simple heptagons over the 135
order-type representatives, externally cross-checked against hamilt07.b08.  The
(E7a) enumeration evaluates `simple` on all 48,600 candidates but never counts
them.  This makes the figure a Lean theorem.

SCOPE.  `simple` is a predicate on chirotopes -- the transcription of
`is_simple` in python/core/geom.py via `seg_cross`.  That it characterises
simplicity for actual polygons in the plane is NOT proved here; see
docs/verification-status.md rows 32 and 34.
-/
"""

Path('lean/SimpleCountDefs.lean').write_text(HDR.format(shard='definition') + """import OTEnumShard
set_option maxRecDepth 4000000
set_option maxHeartbeats 0
namespace Heptagon.SimpleCount
open Heptagon.OrderTypeClassification

/-- How many of the given cyclic orders make representative `i` a simple
heptagon. -/
def countOf (i : Nat) (cs : List (Nat × List Nat)) : Nat :=
  (cs.filter fun p => simple (relabel (orderSigns i) p.2)).length

end Heptagon.SimpleCount
""")

groups = [list(range(a, min(a + REPS, 135))) for a in range(0, 135, REPS)]
names = []
for gi, g in enumerate(groups):
    lit = '[' + ', '.join(str(counts[i]) for i in g) + ']'
    ids = '[' + ', '.join(str(i) for i in g) + ']'
    name = f'SimpleCount{gi:02d}'
    names.append(name)
    Path(f'lean/{name}.lean').write_text(HDR.format(shard=f'representatives {g[0]}..{g[-1]}') +
f"""import SimpleCountDefs
set_option maxRecDepth 4000000
set_option maxHeartbeats 0
namespace Heptagon.SimpleCount
open Heptagon.OrderTypeClassification

theorem counts_{gi} : ({ids} : List Nat).map (fun i => countOf i cyclesIdx) = {lit} := by
  decide +kernel

end Heptagon.SimpleCount
""")

imports = '\n'.join(f'import {n}' for n in names)
lemmas = ', '.join(f'counts_{gi}' for gi in range(len(groups)))
allc = '[' + ', '.join(str(c) for c in counts) + ']'
r135 = '[' + ', '.join(str(i) for i in range(135)) + ']'
ngroups = len(groups)
gcat = ' ++ '.join('[' + ', '.join(str(i) for i in g) + ']' for g in groups)
Path('lean/SimpleCountAll.lean').write_text(HDR.format(shard='assembly') + f"""{imports}
set_option maxRecDepth 4000000
set_option maxHeartbeats 0
namespace Heptagon.SimpleCount
open Heptagon.OrderTypeClassification

/-- The per-representative counts, as one list. -/
def allCounts : List Nat := (List.range 135).map (fun i => countOf i cyclesIdx)

/-- The 135 indices split into the {ngroups} groups the shards cover.  Kept as a
named theorem so the rewrite happens before `simp` can flatten the appends. -/
theorem range135_split : (List.range 135 : List Nat) = {gcat} := by decide

theorem allCounts_eq : allCounts = {allc} := by
  rw [allCounts, range135_split]
  simp only [List.map_append, {lemmas}]
  rfl

/-- **There are exactly 6,342 simple heptagons** over the 135 order-type
representatives and their 360 cyclic vertex orders. -/
theorem simple_total : allCounts.sum = 6342 := by
  rw [allCounts_eq]; rfl

end Heptagon.SimpleCount
""")
print(f'wrote SimpleCountDefs + {len(names)} shards + SimpleCountAll')

lf = Path('lean/lakefile.toml'); s = lf.read_text()
MARK = '\n# --- BEGIN generated simple-count shards ---\n'
END = '# --- END generated simple-count shards ---\n'
if MARK in s:
    s = s[:s.index(MARK)] + s[s.index(END) + len(END):]
allnames = ['SimpleCountDefs'] + names + ['SimpleCountAll']
s = s.rstrip('\n') + '\n' + MARK + '# Generated by python3 python/classification/gen_lean_simple_count.py\n' \
    + ''.join(f'\n[[lean_lib]]\nname = "{n}"\n' for n in allnames) + END
m = re.search(r'defaultTargets = \[([^\]]*)\]', s)
cur = [x.strip().strip('"') for x in m.group(1).split(',')]
cur = [c for c in cur if not c.startswith('SimpleCount')] + allnames
s = s[:m.start()] + 'defaultTargets = [' + ', '.join(f'"{c}"' for c in cur) + ']' + s[m.end():]
lf.write_text(s)
libs = re.findall(r'\[\[lean_lib\]\]\s*\nname = "([^"]+)"', s)
dflt = [x.strip().strip('"') for x in re.search(r'defaultTargets = \[([^\]]*)\]', s).group(1).split(',')]
assert sorted(libs) == sorted(dflt), sorted(set(libs) ^ set(dflt))
print(f'lakefile: {len(libs)} libs')
