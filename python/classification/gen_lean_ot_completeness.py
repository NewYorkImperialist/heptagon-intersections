"""Generate the Lean proof that the 135-representative list is COMPLETE.

`data/order_types/order_types_7.json` holds 135 rank-3 chirotope representatives
on 7 elements.  Everything downstream -- including the (E7a) exhaustiveness
enumeration -- quantifies over that list, so "the list is complete" has been an
external obligation.  This module discharges the inductive step of it.

The construction in python/core/chiro.py builds order types stage by stage: a
representative on n-1 elements is extended by giving signs to the C(n-1,2)
triples containing the new element, and the extension is kept if it satisfies
the NECESSARY Grassmann-Plucker and Radon sign conditions.  At n = 7 that is
16 x 2^15 = 524,288 candidates, of which 1,657 survive.

Rather than transcribe `canonical` into Lean and search for a lex-minimum, each
survivor is shipped with an explicit WITNESS -- a vertex permutation and an
optional global sign flip carrying it to a stored representative -- so Lean only
has to verify witnesses, never search for them.

What this does NOT prove: that every rank-3 chirotope on 7 elements restricts,
by deleting an element, to one of the 16 stored six-element representatives.
That is the mathematical content of the induction and is stated as an explicit
hypothesis, not assumed silently.  See the module header it emits.

Usage: python3 python/classification/gen_lean_ot_completeness.py [slice_size]
"""
from pathlib import Path
from itertools import combinations
import pickle, json, hashlib, sys

SLICE = int(sys.argv[1]) if len(sys.argv) > 1 else 1024
assert 32768 % SLICE == 0
NSLICE = 32768 // SLICE

C = pickle.load(open('.cache/ot_completeness.pkl', 'rb'))
base6, base_pos, mask_pos, witnesses = C['base6'], C['base_pos'], C['mask_pos'], C['witnesses']
T7, T6 = C['T7'], C['T6']
otp = Path('data/order_types/order_types_7.json')
ot135 = json.loads(otp.read_bytes())['chirotopes']
DIGEST = hashlib.sha256(otp.read_bytes()).hexdigest()

def pack(vec):
    """35 signs -> 35 bits, bit r set iff the r-th triple has sign +1."""
    return sum(1 << r for r, s in enumerate(vec) if s > 0)

baseBits = []
for d in base6:
    bits = 0
    for t6, pos in zip(T6, base_pos):
        if d[t6] > 0:
            bits |= 1 << pos
    baseBits.append(bits)

stored = [pack(v) for v in ot135]
wpairs = [(w[0], w[1]) for w in witnesses]

gp, radon = [], []
for S in combinations(range(7), 5):
    if 6 not in S: continue
    for a in S:
        rest = [x for x in S if x != a]
        gp.append((a,) + tuple(rest))
for S in combinations(range(7), 4):
    if 6 in S: radon.append(S)
assert len(gp) == 75 and len(radon) == 20, (len(gp), len(radon))

base3 = [0, 15, 25, 31, 34, 35, 35]
BT = sum(b << (6 * a) for a, b in enumerate(base3))

trip_lit = '[' + ', '.join(str(t) for t in combinations(range(7),3)) + ']'
gp_lit = '[' + ',\n   '.join(str(tuple(r)) for r in gp) + ']'
radon_lit = '[' + ',\n   '.join(str(tuple(r)) for r in radon) + ']'

HDR = f"""/-
COMPLETENESS OF THE 135-REPRESENTATIVE ORDER-TYPE LIST -- {{shard}}.
Generated by python3 python/classification/gen_lean_ot_completeness.py
Source: data/order_types/order_types_7.json
SHA-256: {DIGEST}
The kernel checks the Lean transcription, not JSON or the generator.

WHAT IS PROVED.  Every one-point extension of the 16 stored six-element
representatives that satisfies the necessary Grassmann-Plucker and Radon sign
conditions is carried, by an explicit vertex permutation and optional global
sign flip, onto one of the 135 stored seven-element representatives; and all
135 arise.  524,288 candidates, 1,657 survivors.

WHAT IS NOT PROVED.  That every rank-3 chirotope on 7 elements restricts, by
deleting an element, to one of the 16 stored six-element representatives.  That
is the mathematical content of the stage-by-stage induction; it is carried as an
explicit hypothesis of the final statement, never assumed silently.  Nor is
realizability: the 135 are a SUPERSET of the realizable order types, since only
necessary conditions are imposed.  A superset is what the exclusion argument
needs, and `data/order_types/order_types_7.json` says the same.
-/
"""

defs = HDR.format(shard='definitions and data') + f"""import Mathlib.Tactic
set_option maxRecDepth 4000000
set_option maxHeartbeats 0
namespace Heptagon.OTComplete

/-- Lexicographic rank of the increasing triple `a < b < c` among the 35
increasing triples on 7 elements, in closed form. -/
def rk (a b c : Nat) : Nat :=
  let k := b - a - 1
  (({BT} >>> (6*a)) &&& 63) + (k * (6 - a) - k * (k+1) / 2) + (c - b - 1)

/-- The 35 increasing triples on 7 elements, in lexicographic order. -/
def lexTriples : List (Nat × Nat × Nat) := {trip_lit}

theorem rk_eq_lex : ∀ a : Fin 7, ∀ b : Fin 7, ∀ c : Fin 7, a < b → b < c →
    rk a b c = lexTriples.idxOf ((a:Nat),(b:Nat),(c:Nat)) := by decide

/-- The chirotope packed in 35 bits: bit `rk a b c` is set iff `chi(a,b,c) = +1`.
The alternating extension matches `sort3` and `Chi.__call__` in
python/core/chiro.py: sort the arguments, negate once per transposition. -/
def chiB (v : Nat) (a b c : Nat) : Int :=
  if a = b ∨ b = c ∨ a = c then 0 else
  let lo := min a (min b c)
  let hi := max a (max b c)
  let inv := (if a > b then 1 else 0) + (if a > c then 1 else 0) + (if b > c then 1 else 0)
  (if inv % 2 = 0 then 1 else -1) * (if v.testBit (rk lo (a+b+c-lo-hi) hi) then 1 else -1)

/-- The 75 Grassmann-Plucker relations on 5-subsets containing element 6,
as `gp_relations(7, must_contain=6)` produces them. -/
def gpRels : List (Nat × Nat × Nat × Nat × Nat) :=
  {gp_lit}

/-- `gp_ok` of python/core/chiro.py: three nonzero terms summing to zero cannot
all agree in sign. -/
def gpOk (v : Nat) : Bool :=
  gpRels.all fun r =>
    let a := r.1; let b := r.2.1; let c := r.2.2.1; let d := r.2.2.2.1; let e := r.2.2.2.2
    let t1 := chiB v a b c * chiB v a d e
    let t2 := -(chiB v a b d * chiB v a c e)
    let t3 := chiB v a b e * chiB v a c d
    !(t1 == t2 && t2 == t3)

/-- The 20 Radon relations on 4-subsets containing element 6. -/
def radonRels : List (Nat × Nat × Nat × Nat) :=
  {radon_lit}

/-- `radon_ok` of python/core/chiro.py: four terms summing to zero cannot all
agree in sign. -/
def radonOk (v : Nat) : Bool :=
  radonRels.all fun r =>
    let a := r.1; let b := r.2.1; let c := r.2.2.1; let d := r.2.2.2
    let t0 := chiB v b c d
    let t1 := -(chiB v a c d)
    let t2 := chiB v a b d
    let t3 := -(chiB v a b c)
    !(t0 == t1 && t1 == t2 && t2 == t3)

/-- The 16 six-element representatives, each already placed in the 35-bit
seven-element layout: only the 20 triples avoiding element 6 are set. -/
def baseBits : Nat → Nat
{chr(10).join(f'  | {i} => {b}' for i, b in enumerate(baseBits))}
  | _ => 0

/-- Bit positions, within the 35-bit layout, of the 15 triples containing 6. -/
def maskPos : List Nat := {mask_pos}

def spread (m : Nat) : Nat :=
  (List.range 15).foldl (fun acc b =>
    if m.testBit b then acc ||| (1 <<< (maskPos.getD b 0)) else acc) 0

/-- Candidate extension: base representative `i` with the 15 new triples given
signs by the bits of `m`. -/
def cand (i m : Nat) : Nat := baseBits i ||| spread m

/-- One slice of the extension search: which masks in `[k*{SLICE}, (k+1)*{SLICE})`
survive both necessary conditions. -/
def slice (i k : Nat) : List (Nat × Nat) :=
  (List.range {SLICE}).filterMap fun r =>
    let m := k*{SLICE} + r
    if radonOk (cand i m) && gpOk (cand i m) then some (i, m) else none

end Heptagon.OTComplete
"""
Path('lean/OTCompleteDefs.lean').write_text(defs)
print(f'wrote lean/OTCompleteDefs.lean ({len(gp)} GP, {len(radon)} Radon relations)')
print(f'slice size {SLICE}, {16*NSLICE} shards')
pickle.dump({'stored': stored, 'wpairs': wpairs, 'witnesses': witnesses,
             'SLICE': SLICE, 'NSLICE': NSLICE, 'HDR': HDR},
            open('.cache/ot_completeness_lean.pkl', 'wb'))
