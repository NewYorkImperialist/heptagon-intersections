"""Generate lean/OTBridge.lean; run from the repository root.

The completeness proof (OTComplete*) and the classification enumeration
(OTEnum*) both quantify over "the 135 order-type representatives", but they
carry them in different forms: the completeness proof packs each chirotope into
35 bits, the enumeration keeps a list of 35 signs.  Nothing so far says those
are the same 135.  Without that, combining the two results would be an appeal to
the reader's memory rather than a proof.  This module closes the seam.
"""
from pathlib import Path

Path('lean/OTBridge.lean').write_text('''/-
The two forms of "the 135 order-type representatives", identified.
Generated by python3 python/classification/gen_lean_ot_bridge.py

`OTComplete.stored135` packs each chirotope into 35 bits; `OrderTypeClassification.orderSigns`
keeps a list of 35 signs in {-1, +1}.  Both are generated from the same
`data/order_types/order_types_7.json`, but "generated from the same file" is a
fact about the generators, not about the Lean.  `stored135_eq_orderSigns`
makes it a fact about the Lean.
-/
import OTCompleteWitness
import OrderTypeClassification

set_option maxRecDepth 4000000
set_option maxHeartbeats 0
namespace Heptagon.OTBridge
open Heptagon.OTComplete Heptagon.OrderTypeClassification

/-- Unpack a 35-bit chirotope into the sign-vector form the enumeration uses:
bit set means `+1`, bit clear means `-1`. -/
def unpack (v : Nat) : List Int :=
  (List.range 35).map fun r => if v.testBit r then 1 else -1

/-- **The 135 representatives the completeness proof quantifies over are exactly
the 135 the enumeration quantifies over.**  Checked entry by entry for all 135. -/
theorem stored135_eq_orderSigns : ∀ c : Fin 135, unpack (stored135 c) = orderSigns c := by
  decide +kernel

end Heptagon.OTBridge
''')
print('wrote lean/OTBridge.lean')
