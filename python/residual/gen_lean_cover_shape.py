"""The 28 possible degree shapes of an `I = 40` disjointness graph.

    python3 python/residual/gen_lean_cover_shape.py > lean/CoverShape.lean

Seven row degrees, each at least 1, summing to 9: the multiset is
(3,1,1,1,1,1,1) or (2,2,1,1,1,1,1), and placing the heavy rows gives 7 + 21 =
28 vectors.  Those are exactly the four shapes of
`independent/realizability_sweep/coverage_cases.py` at each of the seven
rotations of `P`, which is why there are four covering refutations and not 28.

## Two things about the Lean statement, both learned the hard way

*Not `omega`.*  This is a wide disjunction over a bounded finite space — an
enumeration, not an arithmetic problem.  `omega` on the 28-fold disjunction over
seven natural-number variables did not terminate and drove this machine's load
average to 187.  Retyping the degrees into `Fin 4` makes it decidable and the
kernel settles it directly.

*And `decide` needs room to find its instance.*  With the default budgets the
instance search fails outright ("failed to synthesize Decidable ...") even though
the decision itself is cheap; `synthInstance.maxSize` is the binding one.  Note
what a failure here looks like: the theorem is accepted with `sorryAx`, so the
build error is the only signal -- check `#print axioms`.

*Seven separate arguments, not a function.*  Stated as
`∀ a : Fin 7 → Fin 4, …`, Lean fails to synthesize `Decidable` for the whole
proposition.  Stated as seven `∀ aᵢ : Fin 4`, each quantifier is handled by
`Fintype.decidableForallFintype` in turn and the instance is found.  `4^7 =
16,384` cases either way.

The `.val`s matter at the call site: `(⟨rowDeg V i, _⟩ : Fin 4).val` is
definitionally `rowDeg V i`, so `CoverAll` can pass its hypotheses straight in.
"""
DEGS = [[3, 1, 1, 1, 1, 1, 1], [2, 2, 1, 1, 1, 1, 1],
        [2, 1, 2, 1, 1, 1, 1], [2, 1, 1, 2, 1, 1, 1]]
NAMES = ['one row of degree 3',
         'two rows of degree 2 at cyclic distance 1',
         'two rows of degree 2 at cyclic distance 2',
         'two rows of degree 2 at cyclic distance 3']

A = [f"a{i}" for i in range(7)]
cases = [[DEGS[k][(m - r) % 7] for m in range(7)] for k in range(4) for r in range(7)]

out = ['import Mathlib.Tactic', '',
       '-- Finding the `Decidable` instance for a 28-fold disjunction of 7-fold',
       '-- conjunctions under seven binders runs past the default INSTANCE-SEARCH',
       '-- budgets -- `synthInstance.maxSize` above all.  The kernel work itself is',
       '-- small (16,384 cases).  All four are elaborator limits.',
       'set_option maxHeartbeats 2000000', 'set_option maxRecDepth 100000',
       'set_option synthInstance.maxHeartbeats 1000000',
       'set_option synthInstance.maxSize 4000', '',
       '/-!', '# The degree shape of the disjointness graph', '',
       'Generated by `python3 python/residual/gen_lean_cover_shape.py`.', '',
       'A configuration with 40 crossings has 9 disjoint side pairs, so its seven row',
       'degrees are each at least 1 and sum to 9.  That leaves exactly **28** degree',
       'vectors, and they are the four shapes of',
       '`independent/realizability_sweep/coverage_cases.py` at each of the seven',
       'rotations of `P`:', '']
for k in range(4):
    out.append(f'  {NAMES[k]:<45} 7 placements')
out += ['',
        '## Why `decide`, and why seven arguments', '',
        'This is a wide disjunction over a bounded finite space — an enumeration rather',
        'than an arithmetic problem.  `omega` on the 28-fold disjunction over seven',
        'natural-number variables does not terminate in any usable time.  Over `Fin 4`',
        'the statement is decidable, and `4^7 = 16,384` cases is small for the kernel.',
        '',
        'The degrees are seven separate arguments rather than one `Fin 7 → Fin 4`:',
        'through a function type Lean does not synthesize the `Decidable` instance,',
        'whereas seven quantifiers are each discharged by `Fintype.decidableForallFintype`.',
        '-/', '',
        'namespace Heptagon.Cover', '',
        '/-- **The 28 degree shapes.**  Seven values in `{1,2,3}` summing to 9 form one',
        'of the 28 vectors below. -/',
        'theorem degree_shape : ∀ ' + ' '.join(A) + ' : Fin 4,']
for a in A:
    out.append(f'    1 ≤ {a}.val →')
out.append('    ' + ' + '.join(f'{a}.val' for a in A) + ' = 9 →')
lines = []
for d in cases:
    lines.append('    (' + ' ∧ '.join(f'{A[m]}.val = {d[m]}' for m in range(7)) + ')')
out.append(' ∨\n'.join(lines) + ' := by decide')
out += ['', 'end Heptagon.Cover', '',
        '#print axioms Heptagon.Cover.degree_shape']
print('\n'.join(out))
