"""Emit the row-degree clauses of the covering refutations.

    python3 python/residual/gen_lean_rowdeg.py <shard> > lean/CoverRowDeg<shard>.lean
    python3 python/residual/gen_lean_rowdeg.py count

The covering refutations (`CCase00k_false`) fix the degree of each row of the
disjointness graph and then use two clause families per row:

  at most k   no `k+1` of the seven sides of `Q` are all missed
  at least k  no `7-k+1` of them are all met

`independent/realizability_sweep/coverage_cases.py` emits them as

    [[-x for x in c] for c in combinations(lits, k+1)]          # at most
    [ list(c)        for c in combinations(lits, 7-k+1)]        # at least

and this file proves each one, from `CoverCount.row_exists_cross` and
`row_exists_miss`.

The lemmas are generic in the row index `i`, which is what keeps the count
small.  A per-case instantiation would need roughly 730 lemmas across the four
degree shapes; stated for an arbitrary row with a `rowDeg V i = k` hypothesis,
the same content is **120** lemmas covering every row of every case:

    k = 1   C(7,2) = 21 at-most  +  C(7,7) =  1 at-least  =  22
    k = 2   C(7,3) = 35          +  C(7,6) =  7           =  42
    k = 3   C(7,4) = 35          +  C(7,5) = 21           =  56

Only k = 1, 2, 3 occur: seven row degrees each at least 1 summing to 9 forces
the multiset (3,1,1,1,1,1,1) or (2,2,1,1,1,1,1).
"""
import itertools, sys

SHARDS = 6

def lemmas():
    out = []
    for k in (1, 2, 3):
        for S in itertools.combinations(range(7), k + 1):
            out.append(('most', k, S))
        for S in itertools.combinations(range(7), 7 - k + 1):
            out.append(('least', k, S))
    return out

LEMMAS = lemmas()

def render(kind, k, S):
    tag = "_".join(map(str, S))
    name = f"row{'Most' if kind == 'most' else 'Least'}{k}_{tag}"
    lit = (lambda j: f"¬ Miss V i {j}") if kind == 'most' else (lambda j: f"Miss V i {j}")
    call = 'row_exists_cross' if kind == 'most' else 'row_exists_miss'
    why = (f"misses exactly {k} of the seven sides of `Q`, so it cannot miss all "
           f"{len(S)} of these" if kind == 'most' else
           f"misses exactly {k} of the seven sides of `Q`, so it cannot meet all "
           f"{len(S)} of these")
    L = []
    L.append("")
    L.append(f"/-- Row `i` {why}. -/")
    L.append(f"theorem {name} (V : Fin 14 → Pt) (i : Fin 7) (h : rowDeg V i = {k}) :")
    L.append("    " + " ∨ ".join(lit(j) for j in S) + " := by")
    L.append(f"  obtain ⟨j, hj, hp⟩ := {call} V (i := i) (S := "
             + "{" + ", ".join(map(str, S)) + "}) (by rw [h]; decide)")
    L.append("  simp only [Finset.mem_insert, Finset.mem_singleton] at hj")
    L.append("  rcases hj with " + " | ".join("rfl" for _ in S))
    for n in range(len(S)):
        inner = "hp" if n == len(S) - 1 else "Or.inl hp"
        term = "".join("Or.inr (" for _ in range(n)) + inner + ")" * n
        L.append(f"  · exact {term}")
    return "\n".join(L)

arg = sys.argv[1] if len(sys.argv) > 1 else '0'
if arg == 'count':
    print(len(LEMMAS), "lemmas;", " ".join(f"CoverRowDeg{s:02d}" for s in range(SHARDS)))
    sys.exit()

s = int(arg)
mine = [n for n in range(len(LEMMAS)) if n * SHARDS // len(LEMMAS) == s]
out = ["import CoverCount", "", "set_option maxHeartbeats 1000000", "",
       f"/-! Row-degree clauses {mine[0]}-{mine[-1]} of {len(LEMMAS)}, generated by",
       f"`python3 python/residual/gen_lean_rowdeg.py {s}`. -/", "",
       "namespace Heptagon.Cover",
       "open Heptagon.Geometry Finset", ""]
for n in mine:
    out.append(render(*LEMMAS[n]))
out += ["", "end Heptagon.Cover"]
print("\n".join(out))
