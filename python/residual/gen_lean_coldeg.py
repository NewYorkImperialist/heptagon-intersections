"""Emit the column at-most-one clauses, for the `I = 42` covering case.

    python3 python/residual/gen_lean_coldeg.py > lean/CoverColDeg.lean

`I = 42` leaves seven disjoint side pairs, and every row and column degree is
then exactly 1 — a perfect matching.  Its covering core uses, besides the
pattern-avoidance clauses and the row clauses of `CoverRowDeg*.lean`, the
statement that no two sides of `P` both miss the same side of `Q`.

That is 21 lemmas, one per unordered pair of sides of `P`, each from
`CoverCount.col_exists_cross`.  The mirror of `gen_lean_rowdeg.py`'s at-most
family, and like those they quantify over the column index, so 21 cover every
column.

The at-least-one direction is not needed here: `CoverColumn.colClause` already
supplies it, and the `I = 42` core does not cite it at all.
"""
import itertools

out = ["import CoverCount", "", "set_option maxHeartbeats 1000000", "",
       "/-!", "# Column at-most-one clauses", "",
       "Generated by `python3 python/residual/gen_lean_coldeg.py`.",
       "",
       "If side `j` of `Q` misses exactly one side of `P`, it cannot miss two.",
       "-/", "",
       "namespace Heptagon.Cover",
       "open Heptagon.Geometry Finset", ""]

for a, b in itertools.combinations(range(7), 2):
    out.append("")
    out.append(f"/-- Column `j` misses exactly one side of `P`, so not both `{a}` and `{b}`. -/")
    out.append(f"theorem colMost1_{a}_{b} (V : Fin 14 → Pt) (j : Fin 7) (h : colDeg V j = 1) :")
    out.append(f"    ¬ Miss V {a} j ∨ ¬ Miss V {b} j := by")
    out.append(f"  obtain ⟨i, hi, hp⟩ := col_exists_cross V (j := j) (S := "
               + "{" + f"{a}, {b}" + "}) (by rw [h]; decide)")
    out.append("  simp only [Finset.mem_insert, Finset.mem_singleton] at hi")
    out.append("  rcases hi with rfl | rfl")
    out.append("  · exact Or.inl hp")
    out.append("  · exact Or.inr hp")

out += ["", "end Heptagon.Cover"]
print("\n".join(out))
