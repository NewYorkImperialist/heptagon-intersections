"""The covering step, assembled: no configuration has 40 crossings.

    python3 python/residual/gen_lean_cover_all.py > lean/CoverAll.lean

Combines `CoverShape.degree_shape` -- seven row degrees each at least 1 and
summing to 9 form one of 28 vectors -- with the 28 `coverCase<k>r<r>` theorems,
one per vector.
"""
DEGS = [[3, 1, 1, 1, 1, 1, 1], [2, 2, 1, 1, 1, 1, 1],
        [2, 1, 2, 1, 1, 1, 1], [2, 1, 1, 2, 1, 1, 1]]

cases = [(k, r) for k in range(4) for r in range(7)]

out = ["import CoverShape"]
out += [f"import CoverCase{k}{r}" for k, r in cases]
out += ["", "set_option maxHeartbeats 1000000", "",
        "/-!", "# The covering step", "",
        "Generated by `python3 python/residual/gen_lean_cover_all.py`.",
        "",
        "A configuration whose two heptagons cross 40 times has 9 disjoint side",
        "pairs, so its seven row degrees are each at least 1 and sum to 9.  There",
        "are 28 such degree vectors (`CoverShape.degree_shape`), and each is",
        "refuted by one of the 28 `coverCase<k>r<r>` theorems.",
        "",
        "## What this assumes, and why",
        "",
        "`hcol` -- every side of `Q` misses some side of `P` -- is carried as a",
        "hypothesis rather than proved.  The project *does* prove it, in",
        "`DisjointnessGraph.exists_disjointO_Pside`, but for a `Config`, and these",
        "theorems are stated for a bare `V : Fin 14 → Pt` with a general-position",
        "hypothesis `GP` that is stronger than what `Config` supplies.  Connecting",
        "them is the same piece of work as closing the general-position gap of",
        "`docs/residual-412-lean.md` §4, and it is not done.  See `CoverColumn.lean`.",
        "-/", "",
        "namespace Heptagon.Cover",
        "open Heptagon.Geometry Heptagon.ResidualSym", ""]

out += ["/-- **The covering step.**  No configuration of fourteen points in general",
        "position, tracing two simple heptagons, has exactly nine disjoint side pairs",
        "— equivalently, none has exactly 40 properly crossing side pairs.",
        "",
        "`hcol` is the one non-geometric hypothesis; see the note above. -/",
        "theorem no_nine_edges (V : Fin 14 → Pt) (hGP : GP V)",
        "    (hSP : SimpleP V) (hSQ : SimpleQ V)",
        "    (hcol : ∀ j : Fin 7, 0 < colDeg V j)",
        "    (hrow : ∀ i : Fin 7, 0 < rowDeg V i)",
        "    (htot : rowDeg V 0 + rowDeg V 1 + rowDeg V 2 + rowDeg V 3 + rowDeg V 4",
        "      + rowDeg V 5 + rowDeg V 6 = 9) : False := by",
        "  have h0 := hrow 0; have h1 := hrow 1; have h2 := hrow 2; have h3 := hrow 3",
        "  have h4 := hrow 4; have h5 := hrow 5; have h6 := hrow 6",
        "  -- Each degree is below 4: one of 4 or more would leave the other six, each",
        "  -- at least 1, unable to bring the total down to 9.  Stated one row at a",
        "  -- time rather than by `fin_cases` on a ∀, because `fin_cases` leaves the",
        "  -- index as an anonymous constructor and `omega` then cannot match the goal",
        "  -- against the `hrow i` hypotheses.",
        ] + [f"  have hb{i} : rowDeg V {i} < 4 := by omega" for i in range(7)] + [
        "  -- `(⟨rowDeg V i, _⟩ : Fin 4).val` is definitionally `rowDeg V i`, so the",
        "  -- degree hypotheses and the total pass straight through.",
        "  have hs := degree_shape " + " ".join(f"⟨rowDeg V {i}, hb{i}⟩" for i in range(7)),
        "    " + " ".join(f"(hrow {i})" for i in range(7)) + " htot",
        "  rcases hs with " + " | ".join("h" for _ in cases)]

for k, r in cases:
    d = [DEGS[k][(m - r) % 7] for m in range(7)]
    args = " ".join(f"h.{'2.' * m}1" if m < 6 else "h." + "2." * 5 + "2" for m in range(7))
    out.append(f"  · exact coverCase{k}r{r} V hGP hSP hSQ hcol {args}")

out += ["", "end Heptagon.Cover", "",
        "#print axioms Heptagon.Cover.no_nine_edges"]
print("\n".join(out))
