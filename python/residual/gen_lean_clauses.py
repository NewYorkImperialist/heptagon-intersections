"""Emit Lean proofs of one orbit's core clauses, from the geometry.

    python3 python/residual/gen_lean_clauses.py [k] > lean/ResidualClauses00k.lean

`k` is the orbit index 0..3; the cores have 167/371/242/513 clauses.  Each clause
of the SAT encoding is one of three things, and each is a FACT about integer
point configurations rather than an assumption:

  Grassmann-Plucker  the three products of the Plucker identity sum to zero,
                     so they cannot share a sign
  acyclicity         likewise for the alternating 4-set identity
  pattern            the encoder's `crossing` predicate is literally
                     GeometryDefs.ProperCross, so these follow from the
                     configuration's crossing pattern

Variable v is the lex rank of an increasing triple of the 14 vertices, true iff
`orient > 0`; a literal's sign is the parity of the sort.  That is Enc.lit in
independent/residual_realizability/indep_om.py, read directly.
"""
import itertools, json, sys
sys.path.insert(0, 'independent/residual_realizability')
from indep_om import Enc

K = int(sys.argv[1]) if len(sys.argv) > 1 else 0
TAG = 'core%03d' % K
EXPORT = 'independent/residual_realizability/lean_export'
E = Enc(range(14))
REV = {v: t for t, v in E.var.items()}

inv = json.load(open('independent/residual_realizability/inventory.json'))
g = tuple(inv['representatives'][K])
segs = {i: (i//7*7 + i%7, i//7*7 + (i+1)%7) for i in range(14)}
pat = {(i, 7+j): not bool(g[i] >> j & 1) for i in range(7) for j in range(7)}
for off in (0, 7):
    for i, j in itertools.combinations(range(7), 2):
        if (j-i) % 7 not in (1, 6): pat[off+i, off+j] = False

prov = {}
def note(cl, tag): prov.setdefault(tuple(sorted(cl)), tag)
for five in itertools.combinations(range(14), 5):
    for a in five:
        b, c, d, e = [x for x in five if x != a]
        L = [E.lit(a,b,c), E.lit(a,d,e), E.lit(a,b,d), E.lit(a,c,e), E.lit(a,b,e), E.lit(a,c,d)]
        T = [(a,b,c),(a,d,e),(a,b,d),(a,c,e),(a,b,e),(a,c,d)]
        for bits in itertools.product([False, True], repeat=6):
            if ((bits[0]==bits[1]) == (bits[2]!=bits[3])) and ((bits[2]!=bits[3]) == (bits[4]==bits[5])):
                note([-l if x else l for l, x in zip(L, bits)], ('GP', (a,b,c,d,e), T, L, bits))
for i, j, k, l in itertools.combinations(range(14), 4):
    L = [E.lit(j,k,l), E.lit(i,k,l), E.lit(i,j,l), E.lit(i,j,k)]
    T = [(j,k,l),(i,k,l),(i,j,l),(i,j,k)]
    for bits in itertools.product([False, True], repeat=4):
        if bits[0] == (not bits[1]) == bits[2] == (not bits[3]):
            note([-x if b else x for x, b in zip(L, bits)], ('RADON', (i,j,k,l), T, L, bits))
for (s, t), want in pat.items():
    p, q = segs[s]; r, w = segs[t]
    if len({p,q,r,w}) != 4: continue
    L = [E.lit(p,q,r), E.lit(p,q,w), E.lit(r,w,p), E.lit(r,w,q)]
    T = [(p,q,r),(p,q,w),(r,w,p),(r,w,q)]
    for bits in itertools.product([False, True], repeat=4):
        if ((bits[0]!=bits[1]) and (bits[2]!=bits[3])) == want: continue
        note([-x if b else x for x, b in zip(L, bits)], ('PAT', (s,t,p,q,r,w), T, L, bits, want))

core = [[int(x) for x in l.split() if x != '0']
        for l in open(f'{EXPORT}/{TAG}.cnf') if l.strip() and l[0] not in 'pc']

def O(t): return f"orient (V {t[0]}) (V {t[1]}) (V {t[2]})"
def vprop(v): return f"0 < {O(REV[v])}"
def dis(cl): return " ∨ ".join((f"¬({vprop(-x)})" if x < 0 else vprop(x)) for x in cl)
def parity(t):
    a = list(t); s = 1
    for u in range(3):
        for v in range(2):
            if a[v] > a[v+1]: a[v], a[v+1] = a[v+1], a[v]; s = -s
    return s

L_ = []
def w(x): L_.append(x)

w("import ResidualBridge")
w(f"import ResidualCore{K:03d}")
w("")
w("-- The assembly at the end of this file applies a theorem with several hundred")
w("-- explicit arguments; that outruns the default elaboration budget.  Kernel")
w("-- checking is unaffected by this option.")
w("set_option maxHeartbeats 2000000")
w("")
w("/-!")
w(f"# The {len(core)} core clauses of orbit_{K:03d}, as facts about integer heptagons")
w("")
w(f"Generated by `python3 python/residual/gen_lean_clauses.py {K}`.  Each clause of")
w("the SAT encoding is discharged from geometry: the Grassmann-Plucker and")
w("acyclicity clauses from polynomial identities in the coordinates, the pattern")
w("clauses from the configuration's crossing pattern, which is exactly")
w("`GeometryDefs.ProperCross`.  Nothing here is assumed.")
w("-/")
w("")
w(f"namespace Heptagon.ResidualClauses{K:03d}")
w("open Heptagon.Geometry Heptagon.ResidualBridge")
w("")
w("/-- No three of the fourteen vertices are collinear. -/")
w("abbrev GP (V : Fin 14 → Pt) : Prop :=")
w("  ∀ i j k : Fin 14, i ≠ j → j ≠ k → i ≠ k → orient (V i) (V j) (V k) ≠ 0")
w("")

for idx, cl in enumerate(core, 1):
    tag = prov[tuple(sorted(cl))]
    kind = tag[0]; T = tag[2]; bits = tag[4]
    extra = ""
    if kind == 'PAT':
        s, t, p, q, r, wv = tag[1]; want = tag[5]
        pc = f"ProperCross (V {p}) (V {q}) (V {r}) (V {wv})"
        extra = f" (hX : {pc})" if want else f" (hX : ¬{pc})"
    w("")
    w(f"/-- Core clause {idx}/{len(core)} — {kind}. -/")
    w(f"theorem c{idx} (V : Fin 14 → Pt) (hGP : GP V){extra} :")
    w(f"    {dis(cl)} := by")
    w("  by_contra hc")
    w("  push_neg at hc")
    ns = [f"s{i}" for i in range(len(cl))]
    w(f"  obtain ⟨{', '.join(ns)}⟩ := hc")
    # strict sign of every variable occurring in the clause
    sgn = {}
    for nm, x in zip(ns, cl):
        v = abs(x); i, j, k = REV[v]
        if x < 0:
            sgn[v] = (nm, +1)
        else:
            w(f"  have m{v} : {O(REV[v])} < 0 :=")
            w(f"    lt_of_le_of_ne {nm} (hGP {i} {j} {k} (by decide) (by decide) (by decide))")
            sgn[v] = (f"m{v}", -1)
    # orient at each encoder-order triple, rewritten to its sorted variable
    facts = []
    for n, tri in enumerate(T):
        v = E.var[tuple(sorted(tri))]; par = parity(tri)
        nm, vs = sgn[v]
        srt = tuple(sorted(tri))
        osign = vs * par                      # sign of orient at the encoder's order
        if tri == srt:
            facts.append((tri, nm, osign))
        else:
            rhs = ("-" if par < 0 else "") + O(srt)
            w(f"  have a{n} : {O(tri)} = {rhs} := by simp only [orient]; ring")
            rel = "<" if osign < 0 else ">"
            w(f"  have b{n} : {O(tri)} {rel} 0 := by rw [a{n}]; linarith [{nm}]")
            facts.append((tri, f"b{n}", osign))
    hyps = ", ".join(f for _, f, _ in facts)
    if kind == 'GP':
        a, b, c, d, e = tag[1]
        w(f"  have hid := gp_identity (V {a}) (V {b}) (V {c}) (V {d}) (V {e})")
        w(f"  nlinarith [hid, {hyps}]")
    elif kind == 'RADON':
        i, j, k, l = tag[1]
        w(f"  have hid := radon_identity (V {i}) (V {j}) (V {k}) (V {l})")
        w(f"  linarith [hid, {hyps}]")
    else:
        s, t, p, q, r, wv = tag[1]; want = tag[5]
        f0, f1, f2, f3 = [f for _, f, _ in facts]
        g0, g1, g2, g3 = [s_ for _, _, s_ in facts]
        if want:
            w(f"  obtain ⟨hx1, hx2⟩ := hX")
            w(f"  nlinarith [hx1, hx2, {hyps}]")
        else:
            w(f"  refine absurd ⟨?_, ?_⟩ hX")
            w(f"  · nlinarith [{f0}, {f1}]")
            w(f"  · nlinarith [{f2}, {f3}]")


# ---- assembly: feed the clause proofs to core00K_false ---------------------
# The variable binder order of that theorem is the sorted set of variables over
# the core AND its derived clauses; recompute it the same way.
allv = set()
for l in open(f'{EXPORT}/{TAG}.cnf'):
    if l.strip() and l[0] not in 'pc': allv |= {abs(int(x)) for x in l.split() if x != '0'}
for line in open(f'{EXPORT}/{TAG}.lrat'):
    t = line.split()
    if len(t) > 1 and t[1] == 'd': continue
    z = t.index('0', 1)
    allv |= {abs(int(x)) for x in t[1:z]}
allv = sorted(allv)

pairs = {}
for cl in core:
    tg = prov[tuple(sorted(cl))]
    if tg[0] == 'PAT':
        s_, t_, p_, q_, r_, w_ = tg[1]
        pairs[(s_, t_)] = (p_, q_, r_, w_, tg[5])

def hname(s_, t_): return f"h{s_}_{t_}"

w("")
w("/-! ## Assembly")
w("")
w(f"`{TAG}_false` says the {len(core)} clauses are jointly contradictory; `c1`-`c{len(core)}`")
w("say each of them holds for a configuration of this shape.  Together: no such")
w(f"configuration exists.  Only {len(pairs)} of the 49 side pairs are mentioned, so the")
w("contradiction is local to a window of the two heptagons.")
w("-/")
w("")
w(f"theorem orbit{K:03d}_impossible (V : Fin 14 → Pt) (hGP : GP V)")
for (s_, t_), (p_, q_, r_, w_, want) in sorted(pairs.items()):
    pc = f"ProperCross (V {p_}) (V {q_}) (V {r_}) (V {w_})"
    w(f"    ({hname(s_,t_)} : {pc if want else '¬' + pc})")
w("    : False :=")
w(f"  {TAG}_false")
for v in allv:
    w(f"    ({vprop(v)})")
for idx, cl in enumerate(core, 1):
    tg = prov[tuple(sorted(cl))]
    if tg[0] == 'PAT':
        s_, t_ = tg[1][0], tg[1][1]
        w(f"    (c{idx} V hGP {hname(s_,t_)})")
    else:
        w(f"    (c{idx} V hGP)")

w("")
w(f"end Heptagon.ResidualClauses{K:03d}")
print("\n".join(L_))
